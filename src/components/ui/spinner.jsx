export const Spinner = ({ variant, ...props }) => {
  switch (variant) {
    case 'circle':
      return <Circle {...props} />;
    case 'ellipsis':
      return <Ellipsis {...props} />;
    case 'ring':
      return <Ring {...props} />;
    default:
      return <Default {...props} />;
  }
};
